            name = "Dag",
            kind = ShiftKind.DAY,
            start = "09:00",
            end = "17:00"
        )

        val historical = Assignment(
            employeeId = employee.id,
            date = "2026-08-03",
            shiftTemplateId = day.id,
            source = "history"
        )

        val storage = DesktopStorage(directory)
        storage.save(
            DesktopWorkspace.fromAppState(
                AppState(
